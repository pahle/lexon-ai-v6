// Generates frontend/src/components/chat/indicator/indicator-points.ts: for
// each mark in indicator-geometry.ts, the length of every path and 26 points
// sampled along the mark at (k + 0.5) / 26 of its total length (the
// prototype's `sample`). The browser's SVG path methods do the measuring, so
// this runs in the pinned Playwright Chromium; the output is committed.
//
//   node scripts/generate-indicator-points.mjs
//
// scripts/test/indicator-points.spec.mjs fails when the committed table no
// longer matches the mark paths (SOURCE_HASH).
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from '@playwright/test';
import * as prettier from 'prettier';
import { MARKS } from '../frontend/src/components/chat/indicator/indicator-geometry.ts';

export const DOT_COUNT_EXPECTED = 26;
const root = resolve(import.meta.dirname, '..');
const outPath = resolve(
  root,
  'frontend/src/components/chat/indicator/indicator-points.ts',
);

/** SHA-256 over the mark ids and path strings, in a fixed order. */
export function computeSourceHash(marks) {
  const text = Object.keys(marks)
    .sort()
    .map((id) => `${id}\n${marks[id].paths.join('\n')}`)
    .join('\n\n');
  return createHash('sha256').update(text).digest('hex');
}

const fixed = (n) => n.toFixed(3);

async function main() {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage();
    await page.setContent('<svg xmlns="http://www.w3.org/2000/svg"></svg>');
    const measured = await page.evaluate(
      ({ marks, count }) => {
        const NS = 'http://www.w3.org/2000/svg';
        const svg = document.querySelector('svg');
        const result = {};
        for (const [id, mark] of Object.entries(marks)) {
          const paths = mark.paths.map((d) => {
            const p = document.createElementNS(NS, 'path');
            p.setAttribute('d', d);
            svg.appendChild(p);
            return p;
          });
          const lengths = paths.map((p) => p.getTotalLength());
          const total = lengths.reduce((a, b) => a + b, 0);
          const points = [];
          for (let k = 0; k < count; k += 1) {
            let d = ((k + 0.5) / count) * total;
            let i = 0;
            while (d > lengths[i] && i < lengths.length - 1) {
              d -= lengths[i];
              i += 1;
            }
            const q = paths[i].getPointAtLength(Math.min(d, lengths[i]));
            points.push([q.x, q.y]);
          }
          result[id] = { lengths, points };
        }
        return result;
      },
      { marks: MARKS, count: DOT_COUNT_EXPECTED },
    );

    const ids = Object.keys(MARKS);
    const pointsSrc = ids
      .map(
        (id) =>
          `  ${id}: [${measured[id].points
            .map(([x, y]) => `[${fixed(x)}, ${fixed(y)}]`)
            .join(', ')}],`,
      )
      .join('\n');
    const lengthsSrc = ids
      .map((id) => `  ${id}: [${measured[id].lengths.map(fixed).join(', ')}],`)
      .join('\n');
    const source = `// GENERATED by scripts/generate-indicator-points.mjs. Do not edit.
// Re-run \`node scripts/generate-indicator-points.mjs\` after changing a mark
// path in indicator-geometry.ts.
import type { MarkId } from './indicator-sequence';

export const SOURCE_HASH = '${computeSourceHash(MARKS)}';

export const MARK_POINTS: Record<
  MarkId,
  readonly (readonly [number, number])[]
> = {
${pointsSrc}
};

export const MARK_PATH_LENGTHS: Record<MarkId, readonly number[]> = {
${lengthsSrc}
};
`;
    const options = (await prettier.resolveConfig(outPath)) ?? {};
    const formatted = await prettier.format(source, {
      ...options,
      filepath: outPath,
    });
    writeFileSync(outPath, formatted);
  } finally {
    await browser.close();
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  await main();
}
